export const DEFAULT_LANGUAGE = 'en';
export const SUPPORTED_LANGUAGES = ['en', 'ta'];

export function getDictionary(lang = DEFAULT_LANGUAGE) {
  return translations[lang] || translations[DEFAULT_LANGUAGE];
}

export function getText(path, lang = DEFAULT_LANGUAGE, fallback = '') {
  const parts = path.split('.');
  let cursor = getDictionary(lang);
  for (let index = 0; index < parts.length; index += 1) {
    if (!cursor || typeof cursor !== 'object' || !(parts[index] in cursor)) {
      return fallback;
    }
    cursor = cursor[parts[index]];
  }
  return cursor !== undefined ? cursor : fallback;
}

