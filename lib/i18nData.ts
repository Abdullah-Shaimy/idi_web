export function formatOrigin(text, lang = DEFAULT_LANGUAGE) {
  if (!text) return text;
  if (lang !== 'ta') return text;
  let raw = text.trim();
  if (raw.toLowerCase().startsWith('from ')) {
    raw = raw.slice(5).trim();
  }
  const normalized = raw.toLowerCase();
  const tamilTown = TAMIL_TOWNS[normalized];
  if (tamilTown) {
    return tamilTown + ' ஐச் சேர்ந்தவர்';
  }
  return raw + ' ஐச் சேர்ந்தவர்';
}

export function formatGraduateName(name, lang = DEFAULT_LANGUAGE) {
  if (!name) return name;
  if (lang !== 'ta') {
    return name.replace(/^Al\s*hafil\s*[\.\s]+/i, 'Al Hafil ');
  }
  return name.replace(/^Al\s*hafil\s*[\.\s]+/i, 'அல் ஹாபிள் ');
}

